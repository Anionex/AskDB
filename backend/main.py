    @validator('username')
    def validate_username(cls, v):
        if len(v) < 1 or len(v) > 50:
            raise ValueError('用户名长度必须在1-50字符之间')
        # 用户名只允许字母、数字和下划线
        if not re.match(r'^[a-zA-Z0-9_]+$', v):
            raise ValueError('用户名只能包含字母、数字和下划线')
        return v

