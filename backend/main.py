def send_verification_code(email: str, code: str):
    """发送验证码邮件"""
    try:
        subject = f"{EMAIL_CONFIG['company_name']} - 邮箱验证码"
        body = f'''
        您好！
        
        您的验证码是：{code}
        
        此验证码用于注册 {EMAIL_CONFIG['company_name']} 账户，有效期为10分钟。
        
        如果不是您本人操作，请忽略此邮件。
        
        {EMAIL_CONFIG['company_name']} 团队
        '''
        
        msg = MIMEText(body, 'plain', 'utf-8')
        msg['Subject'] = subject
        msg['From'] = EMAIL_CONFIG['sender_email']
        msg['To'] = email
        
        server = smtplib.SMTP(EMAIL_CONFIG['smtp_server'], EMAIL_CONFIG['smtp_port'])
        server.starttls()
        server.login(EMAIL_CONFIG['sender_email'], EMAIL_CONFIG['sender_password'])
        server.send_message(msg)
        server.quit()
        
        logger.info(f"验证码发送成功: {email}")
        return True
    except Exception as e:
        logger.error(f"发送验证码失败: {e}")
        return False

def generate_verification_code() -> str:
    """生成6位数字验证码"""
    return ''.join([str(secrets.randbelow(10)) for _ in range(6)])

# JWT令牌管理
def create_access_token(username: str, user_id: int) -> str:
    """创建JWT访问令牌"""
    expires = datetime.utcnow() + timedelta(days=JWT_EXPIRATION_DAYS)
    
    payload = {
        "sub": username,  # subject: 用户名
        "user_id": user_id,
        "exp": expires,  # expiration: 过期时间
        "iat": datetime.utcnow()  # issued at: 签发时间
    }
    
    token = jwt.encode(payload, JWT_SECRET_KEY, algorithm=JWT_ALGORITHM)
    return token

def verify_token(credentials: Optional[HTTPAuthorizationCredentials] = Depends(security)) -> Dict:
    """验证JWT令牌"""
    if not credentials:
        logger.error("缺少Authorization header")
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="缺少认证令牌，请先登录"
        )
    
    token = credentials.credentials
    
    try:
        # 解码JWT token
        payload = jwt.decode(token, JWT_SECRET_KEY, algorithms=[JWT_ALGORITHM])
        username = payload.get("sub")
        
        if username is None:
            raise HTTPException(
                status_code=status.HTTP_401_UNAUTHORIZED,
                detail="无效的令牌"
            )
        
        logger.debug(f"验证JWT token成功: {username}")
        
    except jwt.ExpiredSignatureError:
        logger.warning(f"JWT token已过期")
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="令牌已过期，请重新登录"
        )
    except jwt.InvalidTokenError as e:
        logger.error(f"无效的JWT token: {e}")
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="无效的令牌"
        )
    
    # 从数据库验证用户是否存在且处于活跃状态
    conn = get_db_connection()
    user = conn.execute(
        'SELECT * FROM users WHERE username = ?', 
        (username,)
    ).fetchone()
    conn.close()
    
    if not user or not user["is_active"]:
        logger.warning(f"用户不存在或已禁用: {username}")
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="用户不存在或已被禁用"
        )
    
    logger.debug(f"用户验证成功: {username}")
    return dict(user)

