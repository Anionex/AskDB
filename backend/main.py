def process_chat_message(message: str, session_id: str = "web-session", user_context: dict = None):
    """处理聊天消息"""
    try:
        if not HAS_AGENT:
            return {
                "success": False,
                "response": "AskDB Agent模块未加载，无法处理查询"
            }
        
        # 保存用户消息到数据库
        if conversation_db and user_context:
            try:
                conversation_db.add_message(
                    conversation_id=session_id,
                    role='user',
                    content=message
                )
            except ValueError:
                # 会话不存在，先创建会话
                logger.warning(f"会话不存在，自动创建: {session_id}")
                conversation_db.create_conversation(
                    conversation_id=session_id,
                    user_id=user_context.get('id'),
                    username=user_context.get('username'),
                    title='新对话'
                )
                conversation_db.add_message(
                    conversation_id=session_id,
                    role='user',
                    content=message
                )
        
        # 使用 AgentManager 获取或创建 agent（带用户上下文）
        from backend.agents import agent_manager
        agent = agent_manager.get_agent(session_id, use_memory=True, user_context=user_context)
        
        # 处理消息
        response = agent.run(message)
        ai_response = response.content
        
        # 提取工具调用信息
        tool_calls = []
        if hasattr(response, 'messages') and response.messages:
            for msg in response.messages:
                if hasattr(msg, 'tool_calls') and msg.tool_calls:
                    for call in msg.tool_calls:
                        if hasattr(call, 'function'):
                            func = call.function
                            # 解析参数（可能是字符串或字典）
                            args = func.arguments
                            if isinstance(args, str):
                                try:
                                    args = json.loads(args)
                                except:
                                    pass
                            
                            tool_calls.append({
                                'name': func.name,
                                'arguments': args
                            })
        
        # 保存AI响应到数据库（包含工具调用信息）
        if conversation_db:
            metadata = {}
            if tool_calls:
                metadata['tool_calls'] = tool_calls
            
            conversation_db.add_message(
                conversation_id=session_id,
                role='assistant',
                content=ai_response,
                metadata=metadata if metadata else None
            )
            
            # 如果是第一条消息，自动生成标题
            stats = conversation_db.get_conversation_stats(session_id)
            user_messages = stats.get('user_messages') or 0
            if user_messages == 1:
                conversation_db.auto_generate_title(session_id)
        
        return {
            "success": True,
            "response": ai_response,
            "tool_calls": tool_calls
        }
        
    except Exception as e:
        logger.error(f"AI处理失败: {e}")
        error_msg = f"处理查询时出错: {str(e)}"
        
        # 保存错误消息
        if conversation_db:
            try:
                conversation_db.add_message(
                    conversation_id=session_id,
                    role='error',
                    content=error_msg
                )
            except:
                pass
        
        # 检查是否是web搜索相关的错误
        if "event loop" in str(e).lower() or "coroutine" in str(e).lower():
            error_msg = f"Web搜索功能暂时不可用: {str(e)}"
        
        return {
            "success": False,
            "response": error_msg
        }

async def process_chat_message_stream(message: str, session_id: str, user_context: dict = None) -> AsyncGenerator[str, None]:
    """流式处理聊天消息 - 使用真正的流式API，支持实时工具调用显示"""
    try:
        if not HAS_AGENT:
            yield f"data: {json.dumps({'type': 'error', 'content': 'AskDB Agent模块未加载'}, ensure_ascii=False)}\n\n"
            return
        
        # 保存用户消息到数据库
        if conversation_db and user_context:
            try:
                conversation_db.add_message(
                    conversation_id=session_id,
                    role='user',
                    content=message
                )
                # 检查是否是第一条消息，如果是则立即更新标题
                stats = conversation_db.get_conversation_stats(session_id)
                user_messages = stats.get('user_messages') or 0
                logger.info(f"📊 [标题更新检查] session_id={session_id}, user_messages={user_messages}")
                if user_messages == 1:
                    # 检查当前标题是否为"新对话"，如果是则更新为第一条消息
                    conversation = conversation_db.get_conversation(session_id, user_context.get('username'))
                    logger.info(f"📊 [标题更新检查] 当前标题: {conversation.get('title') if conversation else 'None'}")
                    if conversation and conversation.get('title') == '新对话':
                        logger.info(f"🔄 检测到第一条消息，更新会话标题: {session_id}")
                        new_title = conversation_db.auto_generate_title(session_id)
                        logger.info(f"✅ [标题已更新] session_id={session_id}, new_title={new_title}")
                        if new_title:
                            # 立即通知前端标题已更新
                            logger.info(f"📤 [发送标题更新事件] title={new_title}")
                            yield f"data: {json.dumps({'type': 'title_updated', 'title': new_title}, ensure_ascii=False)}\n\n"
                            await asyncio.sleep(0.001)
            except ValueError:
                logger.warning(f"会话不存在，自动创建: {session_id}")
                conversation_db.create_conversation(
                    conversation_id=session_id,
                    user_id=user_context.get('id'),
                    username=user_context.get('username'),
                    title='新对话'
                )
                conversation_db.add_message(
                    conversation_id=session_id,
                    role='user',
                    content=message
                )
                # 新创建的会话，立即更新标题
                logger.info(f"🔄 新会话创建，更新标题: {session_id}")
                new_title = conversation_db.auto_generate_title(session_id)
                if new_title:
                    # 立即通知前端标题已更新
                    yield f"data: {json.dumps({'type': 'title_updated', 'title': new_title}, ensure_ascii=False)}\n\n"
                    await asyncio.sleep(0.001)
        
        from backend.agents import agent_manager
        from agno.agent import RunEvent
        
        agent = agent_manager.get_agent(session_id, use_memory=True, user_context=user_context)
        
        # 使用真正的流式API：stream=True 和 stream_events=True
        # stream_events=True 是关键，用于接收工具调用事件！
        stream = agent.run(message, stream=True, stream_events=True)
        
        # 用于收集完整响应和工具调用信息
        full_response = []
        tool_calls_info = []
        current_content_length = 0  # 记录当前内容长度
        
        logger.info(f"开始处理流式事件，stream_events=True")
        
        # 遍历流式事件
        event_count = 0
        for chunk in stream:
            event_count += 1
            event_type = getattr(chunk, 'event', 'unknown')
            logger.info(f"[事件 {event_count}] {event_type}")
            
            # 处理内容流
            if chunk.event == RunEvent.run_content:
                content = chunk.content
                if content:
                    full_response.append(content)
                    current_content_length += len(content)  # 更新长度
                    # 实时发送内容块
                    yield f"data: {json.dumps({'type': 'content', 'content': content}, ensure_ascii=False)}\n\n"
                    await asyncio.sleep(0.001)  # 微小延迟以避免过载
            
            # 处理工具调用开始事件
            elif chunk.event == RunEvent.tool_call_started:
                logger.info(f"🔧 工具调用开始！")
                tool_name = getattr(chunk.tool, 'tool_name', '')
                tool_args = getattr(chunk.tool, 'tool_args', {})
                logger.info(f"   工具名称: {tool_name}")
                logger.info(f"   工具参数: {tool_args}")
                
                # 解析参数（可能是字符串或字典）
                if isinstance(tool_args, str):
                    try:
                        tool_args = json.loads(tool_args)
                    except:
                        pass
                
                tool_call_data = {
                    'name': tool_name,
                    'arguments': tool_args
                }
                
                # 实时发送工具调用开始事件
                logger.info(f"   发送 tool_call_start 事件")
                yield f"data: {json.dumps({'type': 'tool_call_start', 'data': tool_call_data}, ensure_ascii=False)}\n\n"
                await asyncio.sleep(0.001)
                
                # 记录工具调用信息（包含位置）
                tool_calls_info.append({
                    'name': tool_name,
                    'arguments': tool_args,
                    'result': None,
                    'insertPosition': current_content_length,  # 记录插入位置
                    'status': 'started'
                })
            
            # 处理工具调用完成事件
            elif chunk.event == RunEvent.tool_call_completed:
                tool_name = getattr(chunk.tool, 'tool_name', '')
                tool_result = getattr(chunk.tool, 'result', '')
                
                # 🔒 检测是否需要确认
                try:
                    if isinstance(tool_result, str):
                        result_data = json.loads(tool_result)
                        if result_data.get('needs_confirmation'):
                            # 发送确认请求事件
                            logger.info(f"🔒 检测到需要确认的操作: {tool_name}")
                            yield f"data: {json.dumps({'type': 'needs_confirmation', 'data': result_data}, ensure_ascii=False)}\n\n"
                            await asyncio.sleep(0.001)
                            
                            # 记录确认请求（不继续处理）
                            for tc in tool_calls_info:
                                if tc['name'] == tool_name and tc['result'] is None:
                                    tc['result'] = tool_result
                                    tc['completedPosition'] = current_content_length
                                    tc['status'] = 'needs_confirmation'
                                    break
                            continue  # 跳过正常的结果发送
                except (json.JSONDecodeError, TypeError):
                    pass  # 不是JSON格式，继续正常处理
                
                # 实时发送工具调用结果
                yield f"data: {json.dumps({'type': 'tool_call_result', 'data': {'name': tool_name, 'result': tool_result}}, ensure_ascii=False)}\n\n"
                await asyncio.sleep(0.001)
                
                # 更新工具调用信息中的结果和完成位置
                for tc in tool_calls_info:
                    if tc['name'] == tool_name and tc['result'] is None:
                        tc['result'] = tool_result
                        tc['completedPosition'] = current_content_length  # 记录完成位置
                        tc['status'] = 'completed'
                        break
        
        # 组装完整响应
        ai_response = ''.join(full_response)
        
        # 保存AI响应到数据库（包含工具调用信息）
        if conversation_db:
            metadata = {}
            if tool_calls_info:
                metadata['tool_calls'] = tool_calls_info
            
            conversation_db.add_message(
                conversation_id=session_id,
                role='assistant',
                content=ai_response,
                metadata=metadata if metadata else None
            )
            
            # 备用检查：如果是第一条消息且标题还是"新对话"，则更新标题
            # （主要检查已在保存用户消息后完成，这里作为备用）
            stats = conversation_db.get_conversation_stats(session_id)
            user_messages = stats.get('user_messages') or 0
            if user_messages == 1:
                conversation = conversation_db.get_conversation(session_id, user_context.get('username') if user_context else None)
                if conversation and conversation.get('title') == '新对话':
                    logger.info(f"🔄 [备用检查] 检测到第一条消息，更新会话标题: {session_id}")
                    new_title = conversation_db.auto_generate_title(session_id)
                    if new_title:
                        # 通知前端标题已更新
                        yield f"data: {json.dumps({'type': 'title_updated', 'title': new_title}, ensure_ascii=False)}\n\n"
                        await asyncio.sleep(0.001)
        
        # 🎯 生成智能推荐（在主回复完成后）
        try:
            from backend.query_recommender import query_recommender
            
            logger.info("🎯 开始生成推荐查询...")
            
            # 检查推荐器是否可用
            if not query_recommender.client:
                logger.warning("⚠️ 推荐器未初始化（可能缺少API key），跳过推荐")
            else:
                # 获取对话历史（用于更好的推荐）
                conversation_history = []
                if conversation_db:
                    messages = conversation_db.get_conversation_messages(
                        session_id, 
                        username=user_context.get('username'),
                        limit=10
                    )
                    # 转换为推荐器需要的格式
                    conversation_history = [
                        {"role": msg['role'], "content": msg['content']}
                        for msg in messages[:-2]  # 排除刚刚添加的用户消息和AI回复
                    ]
                
                logger.info(f"📝 对话历史: {len(conversation_history)} 条消息")
                logger.info(f"📝 当前查询: {message[:50]}...")
                logger.info(f"📝 AI回答长度: {len(ai_response)} 字符")
                
                # 生成推荐
                recommendations = query_recommender.generate_recommendations(
                    current_query=message,
                    current_answer=ai_response,
                    conversation_history=conversation_history,
                    max_recommendations=3
                )
                
                if recommendations and len(recommendations) > 0:
                    logger.info(f"✅ 生成了 {len(recommendations)} 条推荐查询: {recommendations}")
                    # 发送推荐事件
                    yield f"data: {json.dumps({'type': 'recommendations', 'data': recommendations}, ensure_ascii=False)}\n\n"
                else:
                    logger.warning("⚠️ 推荐器返回空列表，未生成推荐查询")
                    
        except Exception as e:
            logger.error(f"❌ 生成推荐失败（不影响主功能）: {e}", exc_info=True)
        
        # 发送完成事件
        yield f"data: {json.dumps({'type': 'done'}, ensure_ascii=False)}\n\n"
        
    except Exception as e:
        logger.error(f"流式处理失败: {e}")
        import traceback
        traceback.print_exc()
        yield f"data: {json.dumps({'type': 'error', 'content': str(e)}, ensure_ascii=False)}\n\n"

